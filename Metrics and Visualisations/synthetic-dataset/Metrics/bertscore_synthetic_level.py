import os
import pandas as pd
import json
from bert_score import score

input_directory = '/content/drive/MyDrive/synthetic_dataset/Model_outputs'
output_json_path = '/content/drive/MyDrive/synthetic_dataset/Metrics/bert_scores.json'


os.makedirs(os.path.dirname(output_json_path), exist_ok=True)

# Initialize result dictionary
all_scores = {}


for filename in os.listdir(input_directory):

    filename = os.path.join(input_directory, filename)
    if filename.endswith('.csv'):

        df = pd.read_csv(filename, encoding='utf-8')

        print(f"\nProcessing file: {filename}")

        # Reference sentences
        refs = df.iloc[:, 1].astype(str).tolist()

        # Scores per file
        file_scores = {}

        for col in df.columns[2:]:
            #candidate sentences
            df[col] = df[col].apply(lambda x: [x] if not isinstance(x, list) else x)
            cands = df[col].astype(str).tolist()

            # Compute BERTScore
            P, R, F1 = score(
                cands, refs, lang="en",
                model_type='albert-xxlarge-v1',batch_size=8
            )
            avg_f1 = F1.mean().item()

            print(f"Average F1 for {col}: {avg_f1:.4f}")

            file_scores[col] = {
                'Precision': P.mean().item(),
                'Recall': R.mean().item(),
                'F1': avg_f1
            }

            # save to JSON
            all_scores[f"{filename}"] = file_scores
            print(all_scores)
            with open(output_json_path, 'w', encoding='utf-8') as f:
                json.dump(all_scores, f, indent=4)
            # Clear GPU memory to prevent accumulation
            import gc, torch
            gc.collect()
            torch.cuda.empty_cache()


print("\n All files processed. Scores saved to:")
print(output_json_path)